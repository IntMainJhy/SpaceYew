// Isolated real HTTP check: never edits the owner's local content/config.
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {startServer,stopServer,loginServer} from './server.mjs';
const data=await mkdtemp(path.join(tmpdir(),'site-promotions-'));
let server;
try {
 server=await startServer(data,Number(process.env.PROMOTION_TEST_PORT||3011));
 const cookie=await loginServer(server.base);
 const headers={Origin:server.base,'Content-Type':'application/json',Cookie:cookie};
 const boot=await (await fetch(server.base+'/api/admin/bootstrap',{headers})).json();
 const promotionBar={enabled:true,items:[{title:'隔离验收广告 · 后台可更新',url:'https://example.com/offer',kind:'ad'},{title:'社区推荐',url:'/community',kind:'recommendation'}]};
 const save=value=>fetch(server.base+'/api/admin/config',{method:'POST',headers,body:JSON.stringify({key:'site',value:{...boot.site,promotionBar:value}})});
 assert.equal((await fetch(server.base+'/api/admin/config',{method:'POST',headers:{Origin:server.base,'Content-Type':'application/json'},body:JSON.stringify({key:'site',value:{...boot.site,promotionBar}})})).status,401);
 assert.equal((await save(promotionBar)).status,200);
 const html=await (await fetch(server.base+'/',{headers:{Cookie:'site-locale=zh'}})).text();
 assert.ok(html.includes('隔离验收广告 · 后台可更新'));
 assert.ok(html.includes('class="promotion-label"'));
 assert.ok(html.includes('<span>广告</span>'));
 assert.ok(html.includes('class="icon"'));
 assert.ok(html.includes('社区推荐'));
 assert.ok(html.includes('aria-roledescription="跑马灯"'));
 assert.ok(html.includes('class="promotion-group promotion-clone" aria-hidden="true"'));
 assert.ok(html.includes('tabindex="-1"'));
 assert.ok(html.includes('rel="sponsored noopener noreferrer"'));
 assert.ok(!html.includes('上一条推广'));
 assert.ok(!html.includes('class="appearance-bar"'));
 assert.equal((await save({...promotionBar,items:[{title:'危险链接',url:'javascript:alert(1)',kind:'ad'}]})).status,400);
 assert.equal((await save({enabled:false,items:[]})).status,200);
 assert.ok(!(await (await fetch(server.base+'/',{headers:{Cookie:'site-locale=zh'}})).text()).includes('class="promotion-bar"'));
 assert.equal((await save({enabled:true,items:[{title:'单条广告也持续循环',url:'',kind:'ad'}]})).status,200);
 const single=await(await fetch(server.base+'/',{headers:{Cookie:'site-locale=zh'}})).text();
 assert.ok(single.includes('单条广告也持续循环'));
 assert.ok(single.includes('class="promotion-inner"'));
 assert.ok(single.includes('关闭推广条'));
 assert.ok(!single.includes('暂停推广'));assert.ok(!single.includes('播放推广'));assert.ok(!single.includes('继续推广'));
 // Desktop releases share the authenticated settings save, but need no installer to exist in the fixture.
 const home=async locale=>(await fetch(server.base+'/',{headers:{Cookie:'site-locale='+locale}})).text();
 const downloads=async locale=>{const response=await fetch(server.base+'/downloads',{headers:{Cookie:'site-locale='+locale}});assert.equal(response.status,200);return response.text()};
 assert.ok(single.includes('href="/downloads"'));
 assert.ok(!single.includes('id="downloads"'));assert.ok(!single.includes('class="product-download-options"'));
 assert.ok(!single.includes('href="#downloads"'));assert.ok(!single.includes('href="/#downloads"'));
 assert.ok(!single.includes('macOS 桌面版即将推出'));assert.ok(!single.includes('Windows 桌面版即将推出'));
 assert.ok(!single.includes('macOS 与 Windows 桌面版即将推出。'));
 const pending=await downloads('zh');
 assert.ok(pending.includes('<title>下载桌面端 · SpaceYew</title>'));
 assert.ok(pending.includes('id="downloads"'));
 assert.ok(pending.includes('macOS 桌面版即将推出'));assert.ok(pending.includes('Windows 桌面版即将推出'));
 assert.equal((pending.match(/type="button" class="space-btn" disabled=""/g)||[]).length,2);
 const config=await(await fetch(server.base+'/api/admin/bootstrap',{headers})).json();
 const releaseSave=value=>fetch(server.base+'/api/admin/config',{method:'POST',headers,body:JSON.stringify({key:'site',value:{...config.site,desktopDownloads:value}})});
 const releases={macos:{url:'https://example.com/releases/SpaceYew.dmg',version:'1.0 · Apple silicon'},windows:{url:'',version:''}};
 assert.equal((await releaseSave(releases)).status,200);
 const available=await downloads('en');assert.ok(available.includes('href="'+releases.macos.url+'"'));assert.ok(available.includes('Download for macOS'));assert.ok(available.includes(releases.macos.version));assert.ok(available.includes('Windows desktop app is coming soon'));
 assert.ok(!(await home('en')).includes(releases.macos.url),'installer links stay off the introduction page');
 const persisted=await(await fetch(server.base+'/api/admin/bootstrap',{headers})).json();
 const {desktopDownloads:omitted,...legacy}=persisted.site;
 assert.equal((await fetch(server.base+'/api/admin/config',{method:'POST',headers,body:JSON.stringify({key:'site',value:legacy})})).status,200);
 assert.ok((await downloads('en')).includes('href="'+releases.macos.url+'"'));
 assert.equal((await releaseSave({windows:{url:'https://name:secret@example.com/app.exe'}})).status,400);
 assert.ok((await downloads('en')).includes('href="'+releases.macos.url+'"'));
 assert.equal((await releaseSave({})).status,200);
 const cleared=await downloads('en');assert.ok(!cleared.includes(releases.macos.url));assert.ok(cleared.includes('Coming soon'));
 assert.ok((await downloads('ja')).includes('近日公開'));
 console.log('PASS: introduction page without download modules, dedicated downloads page, owner-only promotions/releases, SSR pending/available/cleared downloads, legacy preservation, locales and unsafe URL rejection; isolated data.');
} finally {if(server)await stopServer(server);await rm(data,{recursive:true,force:true});}
